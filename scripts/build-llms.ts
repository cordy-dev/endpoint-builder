import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);

const HEADER = `# @cordy/endpoint-builder: full documentation

> The README and the migration guide in one file, generated by \`npm run docs:llms\`. See llms.txt for the short rules.`;

/** llms-full.txt = README + migration guide, so the two never drift apart */
export function buildLlmsFull(): string {
	const read = (name: string) => readFileSync(new URL(name, root), "utf8").trim();
	return `${[HEADER, read("README.md"), read("MIGRATION.md")].join("\n\n---\n\n")}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	writeFileSync(new URL("llms-full.txt", root), buildLlmsFull());
	console.log("llms-full.txt written");
}
