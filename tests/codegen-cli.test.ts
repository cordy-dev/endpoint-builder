import { readFileSync } from "node:fs";

import { describe, expect, it } from "vitest";

import { type CliIo, runCli } from "../src/codegen/cli";

const shop = readFileSync("tests/fixtures/shop-3.0.json", "utf8");

function fakeIo(files: Record<string, string> = {}, remote: Record<string, string> = {}) {
	const out: string[] = [];
	const err: string[] = [];
	const written: Record<string, string> = {};
	const io: CliIo = {
		readFile: async (path) => {
			const text = files[path];
			if (text === undefined) throw new Error(`ENOENT: ${path}`);
			return text;
		},
		readFileIfExists: async (path) => written[path] ?? files[path],
		writeFile: async (path, content) => {
			written[path] = content;
		},
		fetchText: async (url) => {
			const text = remote[url];
			if (text === undefined) throw new Error(`${url} answered 404 Not Found`);
			return text;
		},
		stdout: (text) => out.push(text),
		stderr: (text) => err.push(text),
	};
	return { io, out: () => out.join(""), err: () => err.join(""), written };
}

describe("endpoint-builder generate", () => {
	it("prints the client to stdout without --out", async () => {
		const run = fakeIo({ "api.json": shop });
		expect(await runCli(["generate", "api.json"], run.io)).toBe(0);
		expect(run.out()).toContain("export const contract = defineContract(");
		expect(run.out()).toContain("// Generated by @cordy/endpoint-builder from api.json.");
		expect(run.err()).toContain("warning: Callbacks of createPet are ignored");
	});

	it("writes --out, and --check passes only when the file is current", async () => {
		const run = fakeIo({ "api.json": shop });
		expect(await runCli(["generate", "api.json", "--out", "src/api.ts"], run.io)).toBe(0);
		expect(run.written["src/api.ts"]).toContain("export const contract");

		expect(await runCli(["generate", "api.json", "-o", "src/api.ts", "--check"], run.io)).toBe(0);

		run.written["src/api.ts"] += "// edited";
		const stale = await runCli(["generate", "api.json", "--out", "src/api.ts", "--check"], run.io);
		expect(stale).toBe(1);
		expect(run.err()).toContain("src/api.ts is out of date");

		const missing = fakeIo({ "api.json": shop });
		expect(await runCli(["generate", "api.json", "--out", "nope.ts", "--check"], missing.io)).toBe(1);
		expect(missing.err()).toContain("nope.ts is missing");
		expect(missing.written).toEqual({});
	});

	it("passes the options on", async () => {
		const run = fakeIo({ "api.json": shop });
		await runCli(
			["generate", "api.json", "--group=none", "--no-validate", "--prefer", "xml", "--import-from", "../src"],
			run.io,
		);
		expect(run.out()).not.toContain("jsonSchema");
		expect(run.out()).toContain('from "../src";');
		expect(run.out()).toContain("\tlistPets: endpoint");
	});

	it("downloads documents from a URL", async () => {
		const run = fakeIo({}, { "https://example.test/openapi.json": shop });
		expect(await runCli(["generate", "https://example.test/openapi.json"], run.io)).toBe(0);
		expect(run.out()).toContain("from https://example.test/openapi.json.");
		const failed = fakeIo();
		expect(await runCli(["generate", "https://example.test/missing.json"], failed.io)).toBe(1);
		expect(failed.err()).toContain("404");
	});

	it("explains YAML, invalid JSON and invalid documents", async () => {
		const yaml = fakeIo({ "api.yaml": "openapi: 3.0.0\ninfo:\n  title: x\n" });
		expect(await runCli(["generate", "api.yaml"], yaml.io)).toBe(1);
		expect(yaml.err()).toContain("is YAML. Only JSON is supported");

		const broken = fakeIo({ "api.json": "{" });
		expect(await runCli(["generate", "api.json"], broken.io)).toBe(1);
		expect(broken.err()).toContain("api.json is not valid JSON");

		const notSpec = fakeIo({ "api.json": "{}" });
		expect(await runCli(["generate", "api.json"], notSpec.io)).toBe(1);
		expect(notSpec.err()).toContain("Not an OpenAPI or Swagger document");

		const missing = fakeIo();
		expect(await runCli(["generate", "gone.json"], missing.io)).toBe(1);
		expect(missing.err()).toContain("ENOENT");
	});

	it.each([
		[["generate"], "Which document?"],
		[["generate", "a.json", "b.json"], "Unexpected argument b.json"],
		[["generate", "a.json", "--nope"], "Unknown option --nope"],
		[["generate", "a.json", "--out"], "--out needs a value"],
		[["generate", "a.json", "--prefer", "yaml"], "--prefer must be one of: json, xml"],
		[["generate", "a.json", "--check"], "--check needs --out"],
		[["frobnicate"], 'Unknown command "frobnicate"'],
	])("rejects bad arguments %j", async (args, message) => {
		const run = fakeIo({ "a.json": shop, "b.json": shop });
		expect(await runCli(args, run.io)).toBe(1);
		expect(run.err()).toContain(message);
	});

	it("shows the usage", async () => {
		const run = fakeIo();
		expect(await runCli(["--help"], run.io)).toBe(0);
		expect(await runCli(["generate", "--help"], run.io)).toBe(0);
		expect(run.out()).toContain("Usage: endpoint-builder generate");
		expect(await runCli([], run.io)).toBe(1);
	});
});
