import { describe, expect, expectTypeOf, it } from "vitest";
import { z } from "zod";

import { createClient, HttpError, NetworkError, ParseError, ValidationError } from "../src";
import { json, mockFetch, readBody } from "./helpers";

const User = z.object({ id: z.number(), name: z.string() });

describe("client basics", () => {
	it("joins baseUrl and path with exactly one slash", async () => {
		const fetch = mockFetch(json({}));
		const variants = [
			["https://api.test", "/users"],
			["https://api.test/", "/users"],
			["https://api.test/", "users"],
			["https://api.test", "users"],
		] as const;
		for (const [baseUrl, path] of variants) {
			await createClient({ baseUrl, fetch }).get(path);
		}
		expect(fetch.calls.map(c => c.url)).toEqual(Array(4).fill("https://api.test/users"));
	});

	it("keeps base path segments and absolute URLs", async () => {
		const fetch = mockFetch(json({}));
		const api = createClient({ baseUrl: "https://api.test/v2", fetch });
		await api.get("/users");
		await api.get("https://other.test/x");
		expect(fetch.calls.map(c => c.url)).toEqual(["https://api.test/v2/users", "https://other.test/x"]);
	});

	it("accepts a base URL string", async () => {
		const fetch = mockFetch(json({}));
		await createClient("https://api.test").with({ fetch }).get("/ping");
		expect(fetch.calls[0]!.url).toBe("https://api.test/ping");
	});

	it("interpolates and encodes path params", async () => {
		const fetch = mockFetch(json({ id: 1, name: "a" }));
		const api = createClient({ baseUrl: "https://api.test", fetch });
		await api.get("/users/:id/files/:name", { params: { id: 1, name: "a b/c" } });
		expect(fetch.calls[0]!.url).toBe("https://api.test/users/1/files/a%20b%2Fc");
	});

	it("serializes query and merges client defaults", async () => {
		const fetch = mockFetch(json([]));
		const api = createClient({ baseUrl: "https://api.test", fetch, query: { lang: "en", page: 1 } });
		await api.get("/users", { query: { page: 2, tags: ["a", "b"], filter: { role: "admin" }, skip: undefined } });
		expect(fetch.calls[0]!.url).toBe("https://api.test/users?lang=en&page=2&tags=a&tags=b&filter%5Brole%5D=admin");
	});

	it("sends JSON bodies with content-type", async () => {
		const fetch = mockFetch(json({ id: 1, name: "a" }, { status: 201 }));
		const api = createClient({ baseUrl: "https://api.test", fetch });
		const user = await api.post("/users", { json: { name: "a" } }).returns(User);
		expect(user).toEqual({ id: 1, name: "a" });
		expect(fetch.calls[0]!.method).toBe("POST");
		expect(fetch.calls[0]!.headers.get("content-type")).toBe("application/json");
		expect(await readBody(fetch.calls[0]!.body)).toBe("{\"name\":\"a\"}");
	});

	it("passes native bodies through untouched", async () => {
		const fetch = mockFetch(json({}));
		const api = createClient({ baseUrl: "https://api.test", fetch });
		const form = new FormData();
		form.append("file", new Blob(["x"]), "x.txt");
		await api.post("/upload").body(form);
		await api.post("/raw").body("plain text");
		await api.post("/bytes").body(new Uint8Array([1, 2]));
		expect(fetch.calls[0]!.body).toBe(form);
		expect(fetch.calls[0]!.headers.has("content-type")).toBe(false);
		expect(fetch.calls[1]!.body).toBe("plain text");
		expect(fetch.calls[2]!.body).toBeInstanceOf(Uint8Array);
	});

	it("encodes url-encoded and multipart forms", async () => {
		const fetch = mockFetch(json({}));
		const api = createClient({ baseUrl: "https://api.test", fetch, headers: { "content-type": "application/json" } });
		await api.post("/form").form({ a: 1, b: ["x", "y"], skip: undefined });
		await api.post("/multi").multipart({ name: "n", file: new Blob(["data"]) });
		expect(fetch.calls[0]!.body).toBeInstanceOf(URLSearchParams);
		expect(String(fetch.calls[0]!.body)).toBe("a=1&b=x&b=y");
		expect(fetch.calls[1]!.body).toBeInstanceOf(FormData);
		// the boundary must be generated by fetch
		expect(fetch.calls[1]!.headers.has("content-type")).toBe(false);
	});

	it("merges headers: client < request, null removes", async () => {
		const fetch = mockFetch(json({}));
		const api = createClient({ baseUrl: "https://api.test", fetch, headers: { "X-App": "web", "X-Remove": "1" } });
		await api.get("/").header("x-request", "r").headers({ "X-Remove": null, "X-App": "mobile" });
		const headers = fetch.calls[0]!.headers;
		expect(headers.get("x-app")).toBe("mobile");
		expect(headers.get("x-request")).toBe("r");
		expect(headers.has("x-remove")).toBe(false);
		expect(headers.get("accept")).toContain("application/json");
	});

	it("passes extra fetch init options", async () => {
		const fetch = mockFetch(json({}));
		const api = createClient({ baseUrl: "https://api.test", fetch, init: { credentials: "include" } });
		await api.get("/").init({ cache: "no-store" });
		expect(fetch.calls[0]!.init.credentials).toBe("include");
		expect(fetch.calls[0]!.init.cache).toBe("no-store");
	});
});

describe("responses", () => {
	it("decodes JSON, +json, text and empty bodies", async () => {
		const fetch = mockFetch(
			json({ a: 1 }),
			new Response("{\"title\":\"x\"}", { headers: { "content-type": "application/problem+json" } }),
			new Response("hello", { headers: { "content-type": "text/plain" } }),
			new Response(null, { status: 204 }),
		);
		const api = createClient({ baseUrl: "https://api.test", fetch });
		expect(await api.get("/a")).toEqual({ a: 1 });
		expect(await api.get("/b")).toEqual({ title: "x" });
		expect(await api.get("/c")).toBe("hello");
		expect(await api.delete("/d")).toBeUndefined();
	});

	it("reads bodies explicitly", async () => {
		const fetch = mockFetch(new Response("abc", { headers: { "content-type": "application/octet-stream" } }));
		const api = createClient({ baseUrl: "https://api.test", fetch });
		expect(await api.get("/").text()).toBe("abc");
		expect(await (await api.get("/").blob()).text()).toBe("abc");
		expect(new Uint8Array(await api.get("/").arrayBuffer())).toEqual(new TextEncoder().encode("abc"));
		const stream = await api.get("/").stream();
		expect(await new Response(stream).text()).toBe("abc");
	});

	it("does not JSON-parse text responses", async () => {
		const fetch = mockFetch(new Response("{not json but text}", { headers: { "content-type": "text/plain" } }));
		const api = createClient({ baseUrl: "https://api.test", fetch });
		expect(await api.get("/")).toBe("{not json but text}");
	});

	it("throws ParseError for malformed JSON", async () => {
		const fetch = mockFetch(new Response("<html>oops</html>", { headers: { "content-type": "application/json" } }));
		const api = createClient({ baseUrl: "https://api.test", fetch });
		const result = await api.get("/").safe();
		expect(result.error).toBeInstanceOf(ParseError);
		expect((result.error as ParseError).text).toBe("<html>oops</html>");
	});

	it("send() exposes status and headers", async () => {
		const fetch = mockFetch(json({ id: 1, name: "a" }, { status: 201, headers: { "x-total": "5" } }));
		const api = createClient({ baseUrl: "https://api.test", fetch });
		const response = await api.post("/users").returns(User).send();
		expect(response.status).toBe(201);
		expect(response.headers.get("x-total")).toBe("5");
		expect(response.data.name).toBe("a");
		expect(response.request.method).toBe("POST");
	});

	it("raw() returns the native response without status checks", async () => {
		const fetch = mockFetch(json({ message: "nope" }, { status: 404 }));
		const api = createClient({ baseUrl: "https://api.test", fetch });
		const response = await api.get("/").raw();
		expect(response.status).toBe(404);
		expect(await response.json()).toEqual({ message: "nope" });
	});

	it("unwraps envelopes globally and per request", async () => {
		const fetch = mockFetch(json({ data: { id: 1, name: "a" }, meta: {} }));
		const api = createClient({ baseUrl: "https://api.test", fetch, unwrap: (body: { data: unknown }) => body.data });
		expect(await api.get("/").returns(User)).toEqual({ id: 1, name: "a" });
		expect(await api.get("/").unwrap(false)).toEqual({ data: { id: 1, name: "a" }, meta: {} });
		expect(await api.get("/").unwrap((b: { meta: unknown }) => b.meta)).toEqual({});
	});

	it("map() transforms validated data in order", async () => {
		const fetch = mockFetch(json({ id: 1, name: "ann" }));
		const api = createClient({ baseUrl: "https://api.test", fetch });
		const result = await api.get("/")
			.returns(User)
			.map(user => user.name)
			.map(async name => name.toUpperCase());
		expectTypeOf(result).toEqualTypeOf<string>();
		expect(result).toBe("ANN");
	});
});

describe("errors", () => {
	it("throws HttpError with the parsed body", async () => {
		const fetch = mockFetch(json({ message: "missing" }, { status: 404, statusText: "Not Found" }));
		const api = createClient({ baseUrl: "https://api.test", fetch, retry: false });
		const error = await api.get("/users/1").catch((e: unknown) => e);
		expect(error).toBeInstanceOf(HttpError);
		const httpError = error as HttpError;
		expect(httpError.type).toBe("http");
		expect(httpError.status).toBe(404);
		expect(httpError.body).toEqual({ message: "missing" });
		expect(httpError.message).toBe("HTTP 404 Not Found (GET https://api.test/users/1)");
		expect(httpError.request).toEqual({ method: "GET", url: "https://api.test/users/1" });
	});

	it("wraps fetch failures into NetworkError", async () => {
		const fetch = mockFetch(() => { throw new TypeError("fetch failed"); });
		const api = createClient({ baseUrl: "https://api.test", fetch, retry: false });
		const { error } = await api.get("/").safe();
		expect(error).toBeInstanceOf(NetworkError);
		expect((error as NetworkError).cause).toBeInstanceOf(TypeError);
	});

	it("rejects invalid responses with ValidationError", async () => {
		const fetch = mockFetch(json({ id: "1", name: "a" }));
		const api = createClient({ baseUrl: "https://api.test", fetch });
		const { error } = await api.get("/").returns(User).safe();
		expect(error).toBeInstanceOf(ValidationError);
		expect((error as ValidationError).stage).toBe("response");
		expect((error as ValidationError).issues[0]!.path).toEqual(["id"]);
		expect(error!.message).toMatch(/^Invalid response at "id"/);
	});

	it("reports missing path params as ValidationError", async () => {
		const fetch = mockFetch(json({}));
		const api = createClient({ baseUrl: "https://api.test", fetch });
		// @ts-expect-error params are required
		const { error } = await api.get("/users/:id").safe();
		expect(error).toBeInstanceOf(ValidationError);
		expect((error as ValidationError).stage).toBe("params");
		expect(fetch).not.toHaveBeenCalled();
	});

	it("safe() rethrows programming errors", async () => {
		const fetch = mockFetch(json({ id: 1 }));
		const api = createClient({ baseUrl: "https://api.test", fetch });
		await expect(api.get("/").map(() => { throw new RangeError("bug"); }).safe()).rejects.toBeInstanceOf(RangeError);
	});
});
